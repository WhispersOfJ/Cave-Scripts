#text { color: #@FG@; }

#entry { padding: 8px 10px; border-radius: 10px; margin: 2px 0; }
#entry:selected { background-color: #@ACCENT@; }
#entry:selected #text { color: #@BG@; font-weight: bold; }
TMPL

    # ── swaync.css ───────────────────────────────────────────────
    cat <<'TMPL' | sed_theme > "$D/swaync.css"
