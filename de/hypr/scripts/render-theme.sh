    # ── hyprlock.conf ────────────────────────────────────────────
    cat <<TMPL > "$D/hyprlock.conf"
# hyprlock — $NAME ($DESC) · generated by render-theme.sh
general {
    hide_cursor = true
    ignore_empty_input = true
    # grace period is now a CLI flag (see hyprlock invocations); fade is on
    # by default via the animations system.
}

background {
    monitor = HDMI-A-1
    path = $D/wallpaper.png
    color = rgba($(rgb "$BG"), 1.0)
    blur_passes = 2
    blur_size = 7
}

input-field {
    monitor = HDMI-A-1
    size = 360, 60
    outline_thickness = 2
    dots_size = 0.20
    dots_spacing = 0.35
    dots_center = true
    outer_color = rgba($(rgb "$ACCENT"), 0.9)
    inner_color = rgba($(rgb "$BG"), 0.9)
    font_color = rgba($(rgb "$FG"), 1.0)
    fade_on_empty = true
    check_color = rgba($(rgb "$GREEN"), 1.0)
    fail_color = rgba($(rgb "$RED"), 0.9)
    capslock_color = rgba($(rgb "$YELLOW"), 0.9)
    fail_text = <i>\$FAIL <b>(\$ATTEMPTS)</b></i>
    placeholder_text = <span foreground="##$MUTED">Password…</span>
}

label {
    monitor = HDMI-A-1
    text = \$TIME
    font_family = MesloLGS Nerd Font
    font_size = 42
    color = rgba($(rgb "$FG"), 1.0)
    position = 0, 120
    halign = center
    valign = center
}

label {
    monitor = HDMI-A-1
    text = cmd[update:1000] echo "\$(date +'%A, %d %B  %Y')"
    font_family = MesloLGS Nerd Font
    font_size = 16
    color = rgba($(rgb "$MUTED"), 1.0)
    position = 0, 55
    halign = center
    valign = center
}
TMPL

    # ── alacritty-colors.toml (stack-tui terminal theme) ─────────
    cat <<TMPL | sed_theme > "$D/alacritty-colors.toml"
# alacritty terminal colors — @NAME@ (@DESC@) · generated by render-theme.sh
# Copied to ~/.config/alacritty/colors.toml by hyprtheme; imported from the
# static ~/.config/alacritty/alacritty.toml (font/window settings live there).

[colors.primary]
background = "#@BG@"
foreground = "#@FG@"

[colors.cursor]
cursor = "#@ACCENT@"
text = "#@BG@"

[colors.selection]
background = "#@BG_ALT@"
text = "#@FG@"

# normal.blue/bright.cyan = @ACCENT@ deliberately, so stack-tui's header/
# button chrome ("dark blue" bg) and category labels ("light cyan" fg) pick
# up the theme's signature color, same as borders/highlights everywhere else.
[colors.normal]
black   = "#@BG_ALT@"
red     = "#@RED@"
green   = "#@GREEN@"
yellow  = "#@ORANGE@"
blue    = "#@ACCENT@"
magenta = "#@PURPLE@"
cyan    = "#@BLUE@"
white   = "#@MUTED@"

[colors.bright]
black   = "#@DIM@"
red     = "#@RED@"
green   = "#@GREEN@"
yellow  = "#@YELLOW@"
blue    = "#@BLUE@"
magenta = "#@PURPLE@"
cyan    = "#@ACCENT@"
white   = "#@FG@"
TMPL

    unset -f sed_theme
}
